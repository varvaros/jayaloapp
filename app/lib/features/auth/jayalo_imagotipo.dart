const Color kImagotipoVioleta = Color(0xFF7147F2);

/// Tamaño natural del imagotipo (viewBox del SVG).
const Size kImagotipoSize = Size(374, 136);

/// Parser mínimo de path SVG: solo comandos ABSOLUTOS M, L, Q y Z, separados por
/// espacios (el formato exacto en que está guardado el imagotipo).
Path parseImagotipoPath(String d) {
  final path = Path();
  final tokens = d.split(' ').where((t) => t.isNotEmpty).toList();
  var i = 0;
  double num_() => double.parse(tokens[i++]);
  String cmd = '';
  while (i < tokens.length) {
    final t = tokens[i];
    if (t == 'M' || t == 'L' || t == 'Q' || t == 'Z') {
      cmd = t;
      i++;
      if (cmd == 'Z') path.close();
      continue;
    }
    switch (cmd) {
      case 'M':
        path.moveTo(num_(), num_());
        // coordenadas extra tras una M son L implícitas
        cmd = 'L';
        break;
      case 'L':
        path.lineTo(num_(), num_());
        break;
      case 'Q':
        path.quadraticBezierTo(num_(), num_(), num_(), num_());
        break;
      default:
        throw StateError('comando SVG inesperado: $t');
    }
  }
  return path;
}

/// Paths ya parseados (una sola vez por proceso).
class ImagotipoPaths {
  ImagotipoPaths._();
  static final wordmark = parseImagotipoPath(kImagotipoWordmarkD);
  static final reg = parseImagotipoPath(kImagotipoRegD);
  static final isoTick = parseImagotipoPath(kImagotipoIsoTickD);
  static final cuerpo = parseImagotipoPath(kImagotipoCuerpoD);
  static final ojo = parseImagotipoPath(kImagotipoOjoD);
  static final iris = parseImagotipoPath(kImagotipoIrisD);
}

/// Pinta el imagotipo completo dentro de [target] (encaje proporcional, como el
/// SVG original: wordmark + ® + isotipo con su ojo e iris).
void paintImagotipo(Canvas canvas, Rect target) {
  final s = target.width / kImagotipoSize.width;
  canvas.save();
  canvas.translate(target.left, target.top);
  canvas.scale(s);

  final fill = Paint()..color = kImagotipoVioleta;
  canvas.drawPath(ImagotipoPaths.wordmark, fill);
  canvas.drawPath(
    ImagotipoPaths.reg,
    Paint()
      ..color = kImagotipoVioleta
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1
      ..strokeJoin = StrokeJoin.round
      ..strokeCap = StrokeCap.round,
  );

  // Isotipo: mismo anidado de transforms que el SVG.
  canvas.save();
  canvas.translate(21.4, 26.45);
  canvas.scale(0.767852783203125);
  canvas.drawPath(
    ImagotipoPaths.isoTick,
    Paint()
      ..color = kImagotipoVioleta
      ..style = PaintingStyle.stroke
      ..strokeWidth = 3
      ..strokeJoin = StrokeJoin.round
      ..strokeCap = StrokeCap.round,
  );
  canvas.drawPath(ImagotipoPaths.cuerpo, fill);
  canvas.save();
  canvas.translate(5.75, 25.45);
  canvas.drawPath(ImagotipoPaths.ojo, Paint()..color = const Color(0xFFFFFFFF));
  canvas.restore();
  canvas.save();
  canvas.translate(24.05, 35.9);
  canvas.drawPath(ImagotipoPaths.iris, fill);
  canvas.restore();
  canvas.restore();

  canvas.restore();
}
